  getCategoryIcon(cat) {
    if (!cat) return this.icons.OtherFacilities;
    const clean = cat.replace(/\s+/g, '');
    if (this.icons[clean]) return this.icons[clean];
    if (cat.toLowerCase().includes('library')) return this.icons.Library;
    if (cat.toLowerCase().includes('stationery') || cat.toLowerCase().includes('print')) return this.icons.Stationery;
    if (cat.toLowerCase().includes('lab') || cat.toLowerCase().includes('computer')) return this.icons.ComputerLab;
    if (cat.toLowerCase().includes('cafe') || cat.toLowerCase().includes('food') || cat.toLowerCase().includes('dining')) return this.icons.Cafeteria;
    if (cat.toLowerCase().includes('admin') || cat.toLowerCase().includes('office')) return this.icons.AdministrativeOffice;
    return this.icons.OtherFacilities;
  },

  renderStatusBadge(status) {
    const s = (status || 'Available').toLowerCase();
    let label = 'Available';
    let cls = 'status-available';

    if (s.includes('mod')) {
      label = 'Moderate Crowd';
      cls = 'status-moderate';
    } else if (s.includes('crowd')) {
      label = 'Crowded';
      cls = 'status-crowded';
    } else if (s.includes('close')) {
      label = 'Closed';
      cls = 'status-closed';
    }

    return `
      <span class="status-badge ${cls}">
        <span class="status-dot"></span>
        ${label}
      </span>
    `;
  },

  renderOccupancyBar(occupancy = 0, capacity = 100, crowdPct = 0) {
    let fillCls = 'fill-available';
    if (crowdPct >= 80) fillCls = 'fill-crowded';
    else if (crowdPct >= 45) fillCls = 'fill-moderate';

    return `
      <div class="occupancy-bar-wrapper">
        <div class="occupancy-labels">
          <span>Headcount: <strong>${occupancy}</strong> / ${capacity}</span>
          <span style="font-weight: 700;">${crowdPct}%</span>
        </div>
        <div class="progress-track">
          <div class="progress-fill ${fillCls}" style="width: ${Math.min(100, Math.max(4, crowdPct))}%;"></div>
        </div>
      </div>
    `;
  },

  formatWaitTime(minutes, status) {
    if (status && status.toLowerCase().includes('close')) return 'Closed';
    if (minutes === undefined || minutes === null || minutes <= 0) return 'Immediate (0 min)';
    if (minutes === 1) return '~1 min wait';
    return `~${minutes} mins wait`;
  },

  formatRelativeTime(isoString) {
    if (!isoString) return 'Recently';
    try {
      const date = new Date(isoString);
      const now = new Date();
      const diffSecs = Math.floor((now - date) / 1000);
      if (diffSecs < 60) return 'Just now';
      const diffMins = Math.floor(diffSecs / 60);
      if (diffMins < 60) return `${diffMins}m ago`;
      const diffHours = Math.floor(diffMins / 60);
      if (diffHours < 24) return `${diffHours}h ago`;
      return date.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
    } catch (e) {
      return 'Recently';
    }
  },

  showToast(message, type = 'info') {
    let container = document.getElementById('toast-container');
    if (!container) {
      container = document.createElement('div');
      container.id = 'toast-container';
      document.body.appendChild(container);
    }

    const toast = document.createElement('div');
    toast.className = `toast toast-${type}`;

    let icon = this.icons.info;
    if (type === 'success') icon = this.icons.check;
    if (type === 'error') icon = this.icons.close;

    toast.innerHTML = `<span>${icon}</span><span>${message}</span>`;
    container.appendChild(toast);

    setTimeout(() => {
      toast.style.opacity = '0';
      toast.style.transform = 'translateY(10px)';
      toast.style.transition = 'all 0.25s ease';
      setTimeout(() => toast.remove(), 250);
    }, 3200);
  }
